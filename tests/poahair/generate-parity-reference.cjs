'use strict';
const fs = require('node:fs');
const path = require('node:path');
// Pass the POA Studio hair-physics.js path to regenerate outside this workspace.
const H = require(process.argv[2] ? path.resolve(process.argv[2]) : '../../../../outputs/poa-studio/hair-physics.js');

const ticks = 60;
const attachment = frame => ({
  x: 0.13 * Math.sin(frame / 8) + 0.004 * frame,
  z: 0.07 * Math.cos(frame / 11) - 0.002 * frame,
  angle: 0.31 * Math.sin(frame / 13) + 0.0015 * frame,
});
const cases = [
  {
    name: 'chain', kind: '', anchorIndex: 0, triangles: [],
    rigidity: 0.37, damping: 0.23, gravity: 0.81,
    nodes: [{x:0,z:0},{x:0.22,z:0.43},{x:0.51,z:0.62},{x:0.82,z:0.48}],
  },
  {
    name: 'ribbon', kind: '', anchorIndex: 2, triangles: [],
    rigidity: 0.29, damping: 0.41, gravity: 0.73,
    nodes: [{x:-0.31,z:-0.12},{x:0.18,z:0.04},{x:0.63,z:0.31},{x:0.91,z:0.76}],
  },
  {
    name: 'mesh', kind: 'mesh', anchorIndex: 1, triangles: [[0,1,2],[1,3,2]],
    rigidity: 0.34, damping: 0.19, gravity: 0.92,
    nodes: [{x:-0.35,z:-0.18},{x:0.16,z:0.02},{x:0.55,z:0.37},{x:0.94,z:0.79}],
  },
];
const num = n => Number(n).toPrecision(17).replace(/\.0+$/, '.0');
const node = p => `{x = ${num(p.x)}, z = ${num(p.z)}}`;
const att = a => `{x = ${num(a.x)}, z = ${num(a.z)}, angle = ${num(a.angle)}}`;
let out = `package poahair_test\n\n// Generated by node tests/poahair/generate-parity-reference.cjs; do not edit.\n`;
out += `PARITY_TICKS :: ${ticks}\n`;
const attachments = Array.from({length:ticks+1}, (_,i)=>attachment(i*60/60));
out += `import hair "../../core/poahair"\n\nPARITY_ATTACHMENTS: [${ticks+1}]hair.Attachment = {\n${attachments.map(a=>'\t'+att(a)).join(',\n')}\n}\n`;
for (const c of cases) {
  const strand = {name:c.name,color:'#603f29',width:1.5,rigidity:c.rigidity,damping:c.damping,gravity:c.gravity,opacity:1,nodes:c.nodes};
  if (c.kind) { strand.kind=c.kind; strand.anchorIndex=c.anchorIndex; strand.mesh={triangles:c.triangles}; }
  else if (c.anchorIndex) strand.anchorIndex=c.anchorIndex;
  let cache = null;
  const reference = [];
  for (let tick=0;tick<=ticks;tick++) {
    const result = H.step([strand], attachment, tick, 60, cache, c.name);
    cache = result.cache;
    reference.push(...result.paths[0]);
  }
  out += `PARITY_${c.name.toUpperCase()}_NODES: [${c.nodes.length}]hair.Node = {${c.nodes.map(node).join(', ')}}\n`;
  out += `PARITY_${c.name.toUpperCase()}_TRIANGLES: [${c.triangles.length}][3]int = {${c.triangles.map(t=>`{${t.join(', ')}}`).join(', ')}}\n`;
  out += `PARITY_${c.name.toUpperCase()}_EXPECTED: [${reference.length}]hair.Node = {\n${reference.map((p,i)=>'\t'+node(p)+(i+1<reference.length?',':'')).join('\n')}\n}\n`;
}
const target = path.join(__dirname, 'parity_reference.odin');
fs.writeFileSync(target, out);
console.log(`Wrote ${target}`);
